# ------------------------------------- T-decoding (v2.0 P0-5, Phase 2 block 4)
def t_decoding():
    """Chronos-base decoding-configuration sweep: 12-asset aggregate + the
    SPX real-window probe, from the tracked mechanism CSVs; asserted against
    the evidence-pack D14 values."""
    tk = pd.read_csv(ROOT / "results/mechanism/chronos_base_topk.csv")
    pr = pd.read_csv(ROOT / "results/mechanism/chronos_base_probes.csv")
    cfgs = [("topk50", r"top-$k=50$ (pinned vendor default)", "exact_cdf_topk50"),
            ("topk500", r"top-$k=500$", "exact_cdf_topk500"),
            ("untruncated", "untruncated", "exact_cdf_untruncated")]
    spx = pr[pr.asset == "spx"].set_index("method")
    ctx_q01 = float(spx.loc["realized_ctx", "q01"])
    bolt_q01 = float(spx.loc["chronos_bolt_stored", "q01"])
    want_hit = {"topk50": 32.34, "topk500": 7.59, "untruncated": 1.41}   # ep:347
    want_ucs = {"topk50": (0, 0, 0), "topk500": (0, 0, 0),
                "untruncated": (6, 10, 11)}                              # ep:348-349
    want_q01 = {"topk50": -0.093, "topk500": -1.488, "untruncated": -2.475}  # ep:351
    rows = []
    for key, label, meth in cfgs:
        d = tk[tk.config == key]
        h1 = 100.0 * d[d.alpha == 0.01].hit_rate.mean()
        assert_val(f"tab_decoding {key} mean hit", round(h1, 2), want_hit[key], tol=5e-3)
        ucs = [int((d[d.alpha == a].kupiec_p_mc >= 0.05).sum())
               for a in (0.01, 0.025, 0.05)]
        check(f"tab_decoding {key} UC pass", tuple(ucs) == want_ucs[key],
              f"{ucs} != {want_ucs[key]}")
        q01 = float(spx.loc[meth, "q01"])
        assert_val(f"tab_decoding {key} spx q01", round(q01, 3), want_q01[key], tol=5e-4)
        rows.append((label, f"{h1:.2f}\\%", f"{ucs[0]}/12", f"{ucs[1]}/12",
                     f"{ucs[2]}/12", f"${q01:.3f}$"))
    assert_val("tab_decoding spx ctx q01", round(ctx_q01, 3), -4.956, tol=5e-4)
    assert_val("tab_decoding spx bolt clamp q01", round(bolt_q01, 3), -1.120, tol=5e-4)
    body = [
        r"\begin{table}[tbp]",
        r"\centering",
        r"\caption{Chronos-base by decoding configuration on the 12-asset",
        r"mechanism sub-panel: mean violation rate of the nominal 1\% VaR,",
        r"MC-calibrated UC passes at the three tail levels, and the exact",
        r"categorical-CDF 1\% quantile on the SPX probe window (2021-03-31),",
        r"whose realized context 1\% quantile is $-4.956$ and whose stored",
        r"Chronos-Bolt clamp value is $-1.120$. One forward pass per window;",
        r"the top-$k=50$ row reproduces the delivered sampled E0 read",
        r"(32.34\% exact vs.\ 32.40\% sampled).}",
        r"\label{tab:decoding}",
        r"\small",
        # v2.0 Phase-4 micro-round: natural width exceeds the named build's
        # text block by ~74pt (colsep/font rungs arithmetically insufficient)
        # -> \resizebox to \textwidth; no-op-scale in the wider blinded layout.
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{@{}lccccc@{}}",
        r"\toprule",
        r"decoding & mean hit ($\alpha=1\%$) & UC 1\% & UC 2.5\% & UC 5\% & spx $q_{01}$ \\",
        r"\midrule",
    ]
    for r in rows:
        body.append(" & ".join(r) + r" \\")
    body += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    write_tex("tab_decoding.tex", "\n".join(body))


