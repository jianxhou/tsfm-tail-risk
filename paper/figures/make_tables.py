def t_var_audit_alpha():
    """v1.5 item 1d (signer-directed): per-alpha Kupiec non-rejection rates at
    E3 plus the share of assets passing at all three levels simultaneously.
    Reference values recomputed independently by the signer; the asserts
    below must hit digit-for-digit (stop-and-report otherwise)."""
    bt = pd.read_csv(S4 / "backtests.csv")
    e3 = bt[bt.erule == "e3"]
    rows = {}
    for m in TSFM:
        d = e3[e3.forecaster == m]
        pooled = (d.kupiec_p_mc > 0.05).mean()
        per_a = [(d[d.alpha == a].kupiec_p_mc > 0.05).mean()
                 for a in (0.01, 0.025, 0.05)]
        all3 = (d.assign(ok=d.kupiec_p_mc > 0.05)
                 .groupby("asset").ok.sum() == 3).mean()
        rows[m] = (pooled, *per_a, all3)
