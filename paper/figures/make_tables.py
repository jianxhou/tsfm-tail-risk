# ---------------------------------------------------------------- T1 taxonomy
def _headtype(ht: str) -> str:
    """Display form of the registry head-type identifier (v2.0 Phase-3
    P2-11: math-italic t, consistent with the prose's GARCH(1,1)-$t$)."""
    return {"parametric_student_t": r"parametric Student $t$"}.get(
        ht, tex_escape(ht.replace("_", " ")))


def _brk_tokens(s: str) -> str:
    """Hyphenated registry tokens get break points so the RaggedRight
    columns can wrap them (v2.0 Phase-3 P2-11 hyphenation fix)."""
    return tex_escape(str(s)).replace("-", r"-\allowbreak ")


